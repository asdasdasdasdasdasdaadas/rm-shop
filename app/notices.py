def public_notices() -> dict[str, str]:
    raw = shop_overlay().get("notices")
    overlay = raw if isinstance(raw, dict) else {}
    out: dict[str, str] = {}
    for key, default in DEFAULT_NOTICES.items():
        val = overlay.get(key)
        text = str(val).strip() if isinstance(val, str) else ""
        out[key] = default if text in (LEGACY_NOTICE_DEFAULTS.get(key), PREVIOUS_NOTICE_DEFAULTS.get(key), ENGAGEMENT_PREVIOUS_DEFAULTS.get(key), BALANCE_PREVIOUS_DEFAULTS.get(key), MENU_PREVIOUS_DEFAULTS.get(key), LOGIN_PREVIOUS_DEFAULTS.get(key)) else text or default
    return out


def notice_text(key: str, **kwargs: Any) -> str:
    tpl = public_notices().get(key) or DEFAULT_NOTICES.get(key) or ""
    data = {k: "" if v is None else (escape(unescape(str(v)), quote=True)
            if k in {"name", "brand", "error", "link", "url"} else v) for k, v in kwargs.items()}
    try:
        return tpl.format_map(_SafeMap(data))
    except Exception:
        return tpl


def validate_notices(raw: Any) -> dict[str, str]:
    src = raw if isinstance(raw, dict) else {}
    out: dict[str, str] = {}
    for key in DEFAULT_NOTICES:
        val = src.get(key)
        text = str(val) if val is not None else ""
        if len(text) > 3500:
            raise ValueError(f"Уведомление «{key}»: слишком длинный текст")
        out[key] = text
    return out


def sub_block(url: str | None) -> str:
    link = (url or "").strip()
    if not link:
        return ""
    return f"\n\nСсылка подписки:\n<code>{link}</code>"
