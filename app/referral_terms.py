"""Public referral terms shared by the bot, FAQ and cabinet."""
from app.config import get_settings
from app.texts import days_text, rub_text


def referral_terms(settings=None) -> dict[str, str]:
    settings = settings or get_settings()
    if not settings.referral_program_enabled:
        return {
            "note": "Реферальная программа приостановлена. Новые награды не начисляются, уже полученный баланс сохраняется.",
            "when": "Во время паузы начислений нет. После включения учитываются только новые оплаты, без выплат за период паузы.",
            "how": (
                "Условия при включении: 50 ₽ за первую оплату нового друга и 5% с каждого его пополнения, включая первое. "
                "Если первая оплата прошла во время паузы, бонус 50 ₽ позже не начисляется."
                if settings.balance_enabled else
                "Начисление бонусных дней приостановлено. Актуальные условия будут доступны после включения программы."
            ),
            "friend": "",
        }
    if settings.balance_enabled:
        friend = max(0, int(settings.referral_invitee_reward_rub or 0))
        return {
            "note": "Награды начисляются только за оплаты во время действия программы.",
            "when": "За первую оплату друга по вашей ссылке — 50 ₽ на баланс. Дополнительно — 5% с каждого его пополнения, включая первое, пока программа активна. За один переход по ссылке награда не начисляется.",
            "how": "50 ₽ начисляются один раз; 5% — с каждого пополнения. Например, за первое пополнение на 300 ₽ вы получите 65 ₽, за следующее на 300 ₽ — 15 ₽. Доли рубля накапливаются до целого рубля.",
            "friend": f"Другу после первой оплаты по вашей ссылке — {rub_text(friend)} на баланс, пока программа активна." if friend else "",
        }
    extra = max(0, int(settings.referral_invitee_days or 0))
    return {
        "note": "Награды начисляются только пока программа активна.",
        "when": f"После первой оплаты друга по вашей ссылке вам начислят {days_text(settings.referral_reward_days)}, пока программа активна. За один переход награды нет.",
        "how": "Оплаты во время паузы не дают награду задним числом.",
        "friend": f"Другу при бесплатном периоде +{days_text(extra)}, пока программа активна." if extra else "",
    }
