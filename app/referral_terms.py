"""Public referral terms shared by the bot, FAQ and cabinet."""
from app.config import get_settings
from app.texts import rub_text


def referral_terms(settings=None) -> dict[str, str]:
    settings = settings or get_settings()
    if not settings.referral_program_enabled:
        return {
            "note": "Реферальная программа приостановлена. Новые награды не начисляются, уже полученный баланс сохраняется.",
            "when": "Во время паузы начислений нет. После включения учитываются только новые оплаты, без выплат за период паузы.",
            "how": (
                "Условия при включении: 50 ₽ за первую оплату нового друга и 5% с каждого его пополнения, включая первое. "
                "Если первая оплата прошла во время паузы, бонус 50 ₽ позже не начисляется."
            ),
            "friend": "",
        }
    friend = max(0, int(settings.referral_invitee_reward_rub or 0))
    return {
        "note": "Награды начисляются только за оплаты во время действия программы.",
        "when": "🎁 За первую оплату друга — 50 ₽. Плюс 5% с каждого его пополнения, включая первое, пока программа активна. Друг должен прийти по вашей ссылке.",
        "how": "50 ₽ за первую оплату + 5% с каждого пополнения. Например, друг впервые пополнил 300 ₽ — вам 65 ₽. Следующие 300 ₽ — ещё 15 ₽. Доли рубля накапливаются до целого рубля.",
        "friend": f"Другу после первой оплаты по вашей ссылке — {rub_text(friend)} на баланс, пока программа активна." if friend else "",
    }
