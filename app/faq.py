from __future__ import annotations

from html import escape

from app.config import get_settings, referral_is_payout
from app.texts import days_text, rub_text


def faq_items(*, trial_days: int | None = None) -> list[dict[str, str]]:
    settings = get_settings()
    price = rub_text(settings.vpn_day_price_rub)
    trial = days_text(trial_days if trial_days is not None else settings.trial_days)
    items: list[dict[str, str]] = [
        {
            "q": "VPN не включается. Что сделать?",
            "a": (
                "Нажмите «Открыть кабинет», добавьте устройство и вставьте ссылку в приложение. "
                "Пока устройства нет, подключения не будет — это не поломка."
            ),
        },
    ]
    if settings.balance_enabled:
        if settings.trial_enabled and settings.trial_days > 0:
            items.append(
                {
                    "q": "Пробный период закончится — и всё отключится?",
                    "a": (
                        f"Да, когда баланс кончится. Сейчас на старте обычно {trial}. "
                        "Пополните заранее, не дожидаясь нуля: так проще не потерять доступ. "
                        "Бот открывается даже без VPN."
                    ),
                }
            )
        items.extend(
            [
                {
                    "q": "Когда списывается баланс?",
                    "a": (
                        f"Только с устройств, которые вы сами добавили. "
                        f"Сутки одного устройства — {price}. "
                        "Роутер в этот счёт не входит: у него отдельная оплата на срок. "
                        "Пока устройства нет, деньги лежат. "
                        "Лишние гаджеты лучше не держать — уйдёт быстрее."
                    ),
                },
                {
                    "q": "Отключился и пропал доступ к мессенджеру. Как зайти?",
                    "a": (
                        "Бот открывается без VPN — так и задумано. "
                        "За сутки до конца лучше пополнить или взять обещанный платёж, "
                        "пока мессенджер ещё работает."
                    ),
                },
                {
                    "q": "Можно и телефон, и компьютер?",
                    "a": (
                        "Да, это разные устройства. Каждое списывает свои сутки. "
                        "Не добавляйте лишние — иначе баланс уйдёт быстрее."
                    ),
                },
            ]
        )
    else:
        items.extend(
            [
                {
                    "q": "Как не остаться без доступа?",
                    "a": (
                        "Продлите подписку до даты окончания. "
                        "Бот открывается даже если VPN уже не работает."
                    ),
                },
                {
                    "q": "Отключился и пропал доступ к мессенджеру. Как зайти?",
                    "a": (
                        "Бот открывается без VPN. "
                        "Зайдите из бота и продлите доступ, пока мессенджер ещё работает."
                    ),
                },
                {
                    "q": "Можно и телефон, и компьютер?",
                    "a": "Да. Ссылку подписки добавьте в клиент на каждом устройстве.",
                },
            ]
        )
    items.append(
        {
            "q": "Сменил телефон или переустановил приложение.",
            "a": (
                "Откройте то же устройство в кабинете и заново добавьте подписку. "
                "Если ссылка не берётся — обновите её там же."
            ),
        }
    )
    why = (
        "Устройства, оплата и поддержка в одном месте. "
        "Бот открывается, даже если VPN уже выключен. "
    )
    if settings.balance_enabled:
        why += "Платите только за те устройства, которые сами добавили."
    else:
        why += "Ссылку подписки всегда можно взять или обновить в кабинете."
    items.append({"q": "Как у нас всё устроено?", "a": why})
    if settings.balance_enabled and settings.router_enabled:
        items.append(
            {
                "q": "Как подключить роутер?",
                "a": (
                    f"На главной откройте плашку «Роутер». Слот на {settings.router_days} дней "
                    f"стоит {rub_text(settings.router_rub)}, не списывается с баланса телефонов "
                    "и не занимает лимит устройств. После оплаты создайте устройство и вставьте "
                    "ссылку подписки в Keenetic, OpenWrt или другой клиент роутера."
                ),
            }
        )
    if settings.balance_enabled:
        rub = rub_text(settings.referral_reward_rub)
        when_a = (
            "После первой оплаты друга по вашей ссылке. "
            "Пока друг только пришёл или взял бесплатный период, награды не будет."
        )
        how_a = (
            f"Вам {rub} на баланс за каждого, кто оплатил. "
            "Другу за переход эти деньги не начисляются."
        )
        friend = int(settings.referral_invitee_reward_rub or 0)
        if friend > 0:
            how_a += f" Другу после первой оплаты тоже {rub_text(friend)} на баланс."
        if referral_is_payout():
            how_a += (
                f" Вывести можно от {rub_text(settings.referral_payout_min)} реферальных."
            )
        items.append(
            {
                "q": "Как пригласить друга?",
                "a": (
                    "Нажмите «Поделиться» или «Скопировать текст» — готовое сообщение со ссылкой. "
                    "Друг должен открыть бота именно по ней. "
                    "В пересылке другу — про сервис и его бонус за первую оплату, Вам начисление после его оплаты."
                ),
            }
        )
        items.append({"q": "Когда начислят за приглашённого друга?", "a": when_a})
        items.append({"q": "Сколько дают за друга?", "a": how_a})
    elif settings.referral_reward_days > 0:
        mine = days_text(settings.referral_reward_days)
        extra = days_text(settings.referral_invitee_days)
        items.append(
            {
                "q": "Когда начислят за приглашённого друга?",
                "a": (
                    "После первой оплаты друга по вашей ссылке. "
                    "Пока друг только пришёл или взял бесплатный период, дни вам не начислят."
                ),
            }
        )
        items.append(
            {
                "q": "Сколько дают за друга?",
                "a": (
                    f"Вам {mine}. Другу при бесплатном периоде +{extra}. "
                    "За переход деньги не даём."
                ),
            }
        )
    if settings.balance_enabled and settings.trial_enabled and settings.trial_days > 0:
        items.append(
            {
                "q": "Можно сначала попробовать и уйти?",
                "a": (
                    f"Да. На старте обычно {trial} на балансе. "
                    "Пока устройства нет, ничего не списывается. "
                    "Если не зайдёт — просто не пополняйте."
                ),
            }
        )
    items.append(
        {
            "q": "Где писать, если что-то не так?",
            "a": (
                "В поддержку — кнопка рядом. Можно прикрепить скриншот. "
                "Ответ придёт и сюда, и в чат бота — не нужно искать отдельный канал."
            ),
        }
    )
    return items


def faq_html() -> str:
    lines = ["<b>Частые вопросы</b>", ""]
    for item in faq_items():
        lines.append(f"<b>{escape(item['q'])}</b>")
        lines.append(escape(item["a"]))
        lines.append("")
    lines.append("Если не помогло — напишите в поддержку.")
    return "\n".join(lines).strip()
